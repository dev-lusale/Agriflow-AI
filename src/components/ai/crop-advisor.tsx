"use client";

import * as React from "react";
import { Bot, Loader2, Sparkles } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Alert, Badge } from "@/components/ui/primitives";
import { Dialog, DialogContent } from "@/components/ui/dialog";
import { cropAdviceAction } from "@/server/actions/ai";
import type { AdvisorResult } from "@/server/ai/prompts";

/** Opens AI crop advice for one crop record (Grok, using the record's activities + verified weather). */
export function CropAdvisorButton({ cropRecordId, label }: { cropRecordId: string; label: string }) {
  const [open, setOpen] = React.useState(false);
  const [pending, start] = React.useTransition();
  const [result, setResult] = React.useState<{ advice: AdvisorResult | null; notice?: string; mode: string } | null>(null);

  const run = () =>
    start(async () => {
      setOpen(true);
      setResult(null);
      const res = await cropAdviceAction(cropRecordId);
      if (res.ok && res.data) setResult(res.data);
      else if (!res.ok) {
        toast.error(res.error);
        setOpen(false);
      }
    });

  return (
    <>
      <Button size="sm" variant="secondary" onClick={run} disabled={pending}>
        <Sparkles /> AI advice
      </Button>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent title={`AI crop advisor · ${label}`} description="Recommendations from Grok based on this crop's records and verified weather." wide>
          {pending && (
            <div className="flex items-center gap-3 py-10 text-sm text-navy-600">
              <Loader2 className="size-5 animate-spin text-forest-600" /> Analysing planting date, growth stage, activities and weather…
            </div>
          )}
          {result && !result.advice && <Alert tone="amber" title="AI advice unavailable">{result.notice}</Alert>}
          {result?.advice && (
            <div className="space-y-4">
              <p className="text-sm text-navy-700">{result.advice.summary}</p>
              <ul className="space-y-3">
                {result.advice.recommendations.map((r, i) => (
                  <li key={i} className="rounded-xl border border-border p-3">
                    <div className="flex items-center justify-between gap-2">
                      <p className="font-semibold">{r.title}</p>
                      <Badge tone={r.priority === "HIGH" ? "red" : r.priority === "MEDIUM" ? "amber" : "slate"}>{r.priority.toLowerCase()} priority</Badge>
                    </div>
                    <p className="mt-1 text-sm text-navy-700">{r.detail}</p>
                    <p className="mt-1 text-xs text-navy-500">When: {r.timing}</p>
                  </li>
                ))}
              </ul>
              {result.advice.weather_considerations.length > 0 && (
                <div className="rounded-xl bg-sky-50 p-3 text-sm text-sky-900">
                  <p className="font-semibold">Weather considerations</p>
                  <ul className="mt-1 list-disc pl-5">
                    {result.advice.weather_considerations.map((w, i) => (
                      <li key={i}>{w}</li>
                    ))}
                  </ul>
                </div>
              )}
              {result.advice.uncertainty_note && <p className="text-xs text-navy-500">Uncertainty: {result.advice.uncertainty_note}</p>}
              <p className="flex items-center gap-1 border-t border-border pt-3 text-xs text-navy-500">
                <Bot className="size-3.5" /> Generated by Grok (xAI). Guidance only; confirm with your extension officer before applying chemicals.
              </p>
            </div>
          )}
        </DialogContent>
      </Dialog>
    </>
  );
}
